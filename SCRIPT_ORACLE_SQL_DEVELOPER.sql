CREATE TABLE tb_fornecedores (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_empresa VARCHAR2(150) NOT NULL,
    cnpj VARCHAR2(20) NOT NULL UNIQUE,
    pais VARCHAR2(80) NOT NULL,
    nivel_cadeia VARCHAR2(20) NOT NULL,
    certificado_direitos_humanos NUMBER(1) DEFAULT 1 NOT NULL,
    data_cadastro DATE NOT NULL
);

CREATE TABLE tb_emissoes (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fornecedor_id NUMBER(19) NOT NULL,
    categoria_ambito3 VARCHAR2(100) NOT NULL,
    quantidade_carbono NUMBER(12, 2) NOT NULL,
    tipo_dado VARCHAR2(30) NOT NULL,
    status_auditoria VARCHAR2(30) NOT NULL,
    data_relatorio DATE NOT NULL,
    ativo NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT fk_emissao_fornecedor FOREIGN KEY (fornecedor_id) REFERENCES tb_fornecedores (id)
);

